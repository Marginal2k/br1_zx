"""Recursive-descent Z80 disassembler producing sjasmplus source that reassembles byte-exact.

usage: disasm.py <bin> <org-hex> <out.asm> [--entry hex,hex..] [--inline addr:n,..] [--sym file]
                 [--name X] [--allcode] [--skip n] [--entries-file f]

Code is found by following control flow from the entry points; everything else is emitted as DB.
  --inline 62F9:2   a CALL to that address is followed by n bytes of inline data
  --allcode         linear sweep (treat the whole block as code)
The result is assembled with sjasmplus and compared with the input; an instruction that sjasmplus
encodes differently is emitted as DB.
"""
import sys, os, subprocess, argparse, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dz

SJASM = os.environ.get('SJASMPLUS', r'C:\sjasmplus\sjasmplus.exe')
JP = (0xC3, 0xC2, 0xCA, 0xD2, 0xDA, 0xE2, 0xEA, 0xF2, 0xFA)
CALL = (0xCD, 0xC4, 0xCC, 0xD4, 0xDC, 0xE4, 0xEC, 0xF4, 0xFC)
JR = (0x18, 0x20, 0x28, 0x30, 0x38, 0x10)


def flow(b, a):
    """-> (targets, falls_through)"""
    op = b[0]
    if op in JP: return [b[1] | b[2] << 8], op != 0xC3
    if op in JR: return [(a + 2 + (b[1] - 256 if b[1] > 127 else b[1])) & 0xFFFF], op != 0x18
    if op in CALL: return [b[1] | b[2] << 8], True
    if op in (0xC9, 0xE9): return [], False
    if op in (0xDD, 0xFD) and len(b) > 1 and b[1] == 0xE9: return [], False
    if op == 0xED and len(b) > 1 and b[1] in (0x45, 0x4D, 0x55, 0x5D, 0x65, 0x6D, 0x75, 0x7D): return [], False
    return [], True


def analyse(data, org, entries, inline, allcode=False, bad=()):
    mem = [0] * 65536
    mem[org:org + len(data)] = data
    end = org + len(data)
    ins, owner, calls_inline = {}, {}, {}
    todo = [org] if allcode else list(entries)
    while todo:
        a = todo.pop()
        while org <= a < end and a not in owner:
            i = dz.dis(mem, a, a + 1)[0]
            b = bytes(i.bytes)
            fill = mem[a] in (0x00, 0xFF) and a + 3 < end and mem[a + 1] == mem[a + 2] == mem[a + 3] == mem[a]
            if (a in bad or (fill and not allcode) or a + len(b) > end or i.operation.lower().startswith('def')
                    or any((a + k) in owner for k in range(1, len(b)))):
                if allcode and a + 1 < end:
                    a += 1
                    continue
                break
            ins[a] = (b, i.operation)
            for k in range(len(b)): owner[a + k] = a
            t, ft = flow(b, a)
            nxt = a + len(b)
            for x in t:
                if x in inline and b[0] in CALL:
                    calls_inline[nxt] = inline[x]
                    nxt += inline[x]
                if org <= x < end and not allcode: todo.append(x)
            if not ft and not allcode: break
            a = nxt
    return ins, owner, calls_inline


WORD_RE = re.compile(r'\$([0-9a-f]{4})')


def generate(data, org, ins, owner, calls_inline, syms, name):
    end = org + len(data)
    labels = {}

    def want(addr, kind):
        if org <= addr < end and labels.get(addr) != 'c': labels[addr] = kind

    def operand(a):
        b, op = ins[a]
        m = WORD_RE.search(op)
        if not m: return None, None
        v = int(m.group(1), 16)
        if b[0] in JR: return m, v
        if len(b) >= 3 and (b[-2] | b[-1] << 8) == v: return m, v
        return None, None

    for a in ins:
        m, v = operand(a)
        if m: want(v, 'c' if ins[a][0][0] in JP + CALL + JR else 'd')
    for a, k in calls_inline.items():
        if k == 2: want(data[a - org] | data[a - org + 1] << 8, 'd')
    for v in list(labels):
        base = owner.get(v, v)
        if base != v and base not in labels: labels[base] = 'c'

    def at(v): return syms.get(v) or ('%s_%04X' % ('L' if labels.get(v) == 'c' else 'D', v))

    def lname(v):
        if v in labels:
            base = owner.get(v, v)
            return at(v) if base == v else '%s+%d' % (at(base), v - base)
        return syms.get(v)

    out = ['; %s' % name, '; org $%04X, length $%04X' % (org, len(data)),
           '; generated by tools/disasm.py; reassembles byte-exact with sjasmplus', '', '        ORG $%04X' % org, '']
    a = org
    while a < end:
        if a in labels and owner.get(a, a) == a: out.append('%s:' % at(a))
        if a in ins:
            b, op = ins[a]
            txt = op
            m, v = operand(a)
            if m:
                n = lname(v)
                if n: txt = op[:m.start()] + n + op[m.end():]
            out.append('        %-30s; %04X  %s' % (txt, a, b.hex()))
            a += len(b)
            if a in calls_inline:
                k = calls_inline[a]
                raw = data[a - org:a - org + k]
                if k == 2:
                    v = raw[0] | raw[1] << 8
                    out.append('        %-30s; %04X  inline argument' % ('DW   ' + (lname(v) or '$%04X' % v), a))
                else:
                    out.append('        DB   %s ; %04X  inline' % (','.join('$%02X' % x for x in raw), a))
                a += k
            if b[0] in (0xC3, 0xC9, 0x18, 0xE9): out.append('')
        else:
            e = a + 1
            while e < end and e not in ins and e not in labels and e not in calls_inline and e - a < 16: e += 1
            raw = data[a - org:e - org]
            asc = ''.join(chr(x) if 32 <= x < 127 else '.' for x in raw)
            out.append('        DB   %-80s; %04X  %s' % (','.join('$%02X' % x for x in raw), a, asc))
            a = e
    return '\n'.join(out) + '\n'


def assemble(asm_path, out_bin):
    r = subprocess.run([SJASM, '--nologo', '--msg=err', '--raw=' + out_bin, asm_path], capture_output=True, text=True)
    return r.returncode, (r.stdout + r.stderr)


def load_syms(path):
    syms = {}
    if path and os.path.exists(path):
        for line in open(path):
            line = line.split(';')[0].split()
            if len(line) >= 2: syms[int(line[1].lstrip('$'), 16)] = line[0]
    return syms


def run(binpath, org, out, entries=None, inline=None, sym='', name='', allcode=False, skip=0, quiet=False):
    data = open(binpath, 'rb').read()[skip:]
    entries = entries or [org]
    inline = inline or {}
    syms = load_syms(sym)
    bad = set()
    for attempt in range(200):
        ins, owner, ci = analyse(data, org, entries, inline, allcode, bad)
        src = generate(data, org, ins, owner, ci, syms, name or os.path.basename(binpath))
        ext = {v: n for v, n in syms.items() if not (org <= v < org + len(data))}
        equ = ''.join('%-14s EQU $%04X\n' % (n, v) for v, n in sorted(ext.items()) if re.search(r'\b%s\b' % re.escape(n), src))
        if equ: src = src.replace('        ORG', equ + '\n        ORG', 1)
        open(out, 'w', encoding='utf-8').write(src)
        tmp = out + '.verify.bin'
        rc, msg = assemble(out, tmp)
        if rc != 0:
            print(msg[:2000])
            raise SystemExit('assembly failed: ' + out)
        got = open(tmp, 'rb').read()
        os.remove(tmp)
        if got == data:
            code = sum(len(b) for b, _ in ins.values())
            if not quiet:
                print('%s: OK byte-exact; %d instructions, code %d of %d bytes (%d%%), %d forced DB'
                      % (out, len(ins), code, len(data), 100 * code // max(1, len(data)), len(bad)))
            return dict(instructions=len(ins), code=code, size=len(data))
        i = next((k for k in range(min(len(got), len(data))) if got[k] != data[k]), min(len(got), len(data)))
        addr = owner.get(org + i, org + i)
        if addr in bad or addr not in ins: raise SystemExit('cannot fix mismatch at %04X in %s' % (org + i, out))
        bad.add(addr)
    raise SystemExit('too many mismatches')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('bin'); ap.add_argument('org'); ap.add_argument('out')
    ap.add_argument('--entry', default=''); ap.add_argument('--inline', default=''); ap.add_argument('--sym', default='')
    ap.add_argument('--name', default=''); ap.add_argument('--allcode', action='store_true'); ap.add_argument('--skip', default='0')
    a = ap.parse_args()
    run(a.bin, int(a.org, 16), a.out, [int(x, 16) for x in a.entry.split(',') if x],
        {int(k, 16): int(v) for k, v in (x.split(':') for x in a.inline.split(',') if x)},
        a.sym, a.name, a.allcode, int(a.skip, 0))


if __name__ == '__main__':
    main()
